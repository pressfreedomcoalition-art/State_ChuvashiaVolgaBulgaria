const dict: Record<Lang, Record<I18nKey, string>> = { ru, cv, en };

export type I18nVars = Record<string, string | number | undefined | null>;

let currentLang: Lang = "ru";

export function isLang(v: unknown): v is Lang {
  return v === "ru" || v === "cv" || v === "en";
}

export function mapLanguageCode(code: string | undefined | null): Lang | null {
  if (!code) return null;
  const c = code.trim().toLowerCase().replace(/_/g, "-");
  if (!c) return null;
  if (c === "cv" || c.startsWith("cv-") || c === "chv" || c.startsWith("chv-")) return "cv";
  if (c === "ru" || c.startsWith("ru-")) return "ru";
  return "en";
}

export function detectTelegramLang(): Lang | null {
  return mapLanguageCode(getTelegramLanguageCode());
}

export function resolveInitialLang(): Lang {
  try {
    if (localStorage.getItem(LANG_USER_KEY) === "1") {
      const saved = localStorage.getItem(LANG_KEY);
      if (isLang(saved)) return saved;
    }
  } catch {
    /* ignore */
  }
  return detectTelegramLang() ?? "ru";
}

export function applyLang(lang: Lang, fromUser = false) {
  currentLang = lang;
  try {
    localStorage.setItem(LANG_KEY, lang);
    if (fromUser) localStorage.setItem(LANG_USER_KEY, "1");
  } catch {
    /* ignore */
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang;
    document.title = t(lang, "pageTitle");
  }
}

export function getLang(): Lang {
  return currentLang;
}

export function t(lang: Lang, key: string, vars?: I18nVars) {
  const table = dict[lang] || dict.ru;
  let s = table[key as I18nKey] || dict.ru[key as I18nKey] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, v == null ? "" : String(v));
    }
  }
  return s;
}

export function ttKey(key: string, vars?: I18nVars) {
  return t(currentLang, key, vars);
}
